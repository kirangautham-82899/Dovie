-- Journal storage for docs/crypto-spec.md (v1).
-- The server only ever sees ciphertext and wrapped keys. Mood, date and word
-- count are not secret and are kept in plain columns for the weekly review.

create table public.journal_keys (
  user_id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  kdf_salt bytea not null check (octet_length(kdf_salt) = 16),
  kdf_iterations integer not null check (kdf_iterations >= 600000),
  wrapped_dek text not null,
  wrapped_dek_recovery text not null,
  version smallint not null default 1 check (version = 1),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- The id is generated by the client because it is part of the entry's AAD.
create table public.journal_entries (
  id uuid primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  entry_date date not null default current_date,
  mood smallint check (mood between 1 and 5),
  word_count integer not null default 0 check (word_count between 0 and 100000),
  ciphertext text not null check (char_length(ciphertext) <= 200000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
-- One entry per day; editing today's entry re-encrypts the same row.
create unique index journal_entries_one_per_day on public.journal_entries (user_id, entry_date)
  where deleted_at is null;

do $$
declare t text;
begin
  foreach t in array array['journal_keys','journal_entries'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format(
      'create trigger set_updated_at before update on public.%I
       for each row execute function public.set_updated_at()', t);
    execute format('create policy "%1$s_select_own" on public.%1$I for select using (user_id = auth.uid())', t);
    execute format('create policy "%1$s_insert_own" on public.%1$I for insert with check (user_id = auth.uid())', t);
    execute format('create policy "%1$s_update_own" on public.%1$I for update using (user_id = auth.uid()) with check (user_id = auth.uid())', t);
    execute format('create policy "%1$s_delete_own" on public.%1$I for delete using (user_id = auth.uid())', t);
  end loop;
end $$;
